/** Fast lookup by canonical name. */
export const CATALOG_EVENTS_BY_NAME: ReadonlyMap<string, (typeof CATALOG_EVENTS)[number]> = new Map(
  CATALOG_EVENTS.map((e) => [e.name, e]),
);

export function isCanonicalEventName(name: string): boolean {
  return CATALOG_EVENTS_BY_NAME.has(name);
}

