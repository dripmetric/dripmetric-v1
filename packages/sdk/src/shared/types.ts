/**
 * The wire types, duplicated deliberately.
 *
 * The SDK does NOT import @dripmetric/catalog. The catalog is the server's source of
 * truth and carries Zod schemas and 76 event definitions; pulling it into a bundle
 * with a 5 KB gzipped budget is not possible. Instead the handful of names the SDK
 * sends are literals here, and a test in packages/catalog asserts every one of them
 * exists in the real catalog — so the bundle stays small and the names stay honest.
 */

export type MessageType = 'identify' | 'track' | 'page' | 'group';

export interface Message {
  type: MessageType;
  /** Generated by us, so a retry can never double-count. */
  messageId: string;
  timestamp: string;
  userId?: string | undefined;
  anonymousId?: string | undefined;
  event?: string | undefined;
  name?: string | undefined;
  properties?: Record<string, unknown> | undefined;
  traits?: Record<string, unknown> | undefined;
  groupId?: string | undefined;
  context?: MessageContext | undefined;
}

export interface MessageContext {
  userAgent?: string;
  userAgentData?: {
    mobile?: boolean;
    platform?: string;
    brands?: { brand: string; version: string }[];
  };
  locale?: string;
  timezone?: string;
  page?: { path?: string; title?: string; referrer?: string; search?: string };
  campaign?: { source?: string; medium?: string; name?: string; term?: string; content?: string };
  screen?: { width?: number; height?: number };
  library?: { name: string; version: string };
  consent?: { granted?: boolean; globalPrivacyControl?: boolean };
  sessionId?: string;
  pageViewId?: string;
  userIdHmac?: string;
}

/**
 * The events the browser SDK sends by itself (brief Appendix A).
 * `packages/catalog/src/__tests__/sdk-names.test.ts` proves each is a real
 * catalog name, so a typo here cannot reach a founder's dashboard as a
 * permanently unmapped event.
 */
/**
 * The one automatic event the CORE sends.
 *
 * Separate from AUTO_EVENTS below on purpose: that is a single object, so importing
 * it for one name pulls all twelve strings into the bundle — esbuild cannot
 * tree-shake an object's properties — and the core has a 5 KB budget to keep.
 */
export const PAGE_LEFT = 'Page Left';

/** Everything the lazy chunk sends, plus the two the core handles. */
export const AUTO_EVENTS = {
  pageViewed: 'Page Viewed',
  pageLeft: PAGE_LEFT,
  signupStarted: 'Signup Started',
  formStarted: 'Form Started',
  formSubmitted: 'Form Submitted',
  formAbandoned: 'Form Abandoned',
  formError: 'Form Error',
  pricingInteraction: 'Pricing Interaction',
  planSelected: 'Plan Selected',
  rageClick: 'Rage Click',
  deadClick: 'Dead Click',
  slowPage: 'Slow Page',
} as const;
