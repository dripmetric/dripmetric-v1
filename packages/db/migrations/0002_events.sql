-- 0002_events.sql — M1. The compact event storage of settled decision 3.
--
-- The budget is about 215 bytes per event INCLUDING indexes; a naive text design is
-- about 405 (brief section 4). Three choices do the work:
--
--   1. Event names are dictionary-encoded: `events.name_id` is 4 bytes, not a string.
--   2. Users and anonymous visitors get 4-byte integer keys, not text ids.
--   3. Context is stored once per session, not on every event. That is the difference
--      between ~215 and ~575 bytes.
--
-- Plus: `message_hash` is a uuid (16 bytes, no varlena header) rather than the
-- client's text message id, and the time index is BRIN, which costs almost nothing on
-- an append-ordered table and is exactly what the retention job's range deletes want.

-- ---------------------------------------------------------------------------
-- event_names — each project's raw event names and what they mean.
-- Cached in memory at ingest. Unmapped names are the Inbox (settled decision 10).
-- ---------------------------------------------------------------------------
CREATE TABLE event_names (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  -- Exactly what the founder's code sends, e.g. 'workspace_setup_done'.
  raw_name    text NOT NULL,
  -- One of the dozen canonical meanings, or NULL while it waits in the Inbox.
  canonical   text,
  status      text NOT NULL DEFAULT 'unmapped'
              CHECK (status IN ('unmapped', 'suggested', 'confirmed', 'ignored')),
  confidence  text CHECK (confidence IN ('high', 'medium', 'low')),
  -- Why the model suggested this, shown to the founder before they confirm.
  reason      text,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at  timestamptz NOT NULL DEFAULT now(),
  event_count   bigint NOT NULL DEFAULT 0,
  -- Each canonical event is assigned to exactly one source path, to avoid double
  -- counting (brief section 5). Auto-assigned on first sight.
  owning_source text,
  PRIMARY KEY (project_id, id)
);
CREATE UNIQUE INDEX event_names_project_raw_key ON event_names (project_id, raw_name);
CREATE INDEX event_names_project_canonical_idx ON event_names (project_id, canonical)
  WHERE canonical IS NOT NULL;

-- ---------------------------------------------------------------------------
-- paths — normalised page paths, one row each. Page events store a path_id, so URL
-- rules run over a few hundred rows instead of millions of events (brief section 4).
-- ---------------------------------------------------------------------------
CREATE TABLE paths (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  path        text NOT NULL,
  -- Titles only for marketing hosts and rule pages (brief section 10).
  title       text,
  is_key_page boolean NOT NULL DEFAULT false,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, id)
);
CREATE UNIQUE INDEX paths_project_path_key ON paths (project_id, path);

-- ---------------------------------------------------------------------------
-- end_users — the people using the founder's product. About 320 bytes a row.
-- Emails and name-like traits are envelope-encrypted (brief section 10).
-- ---------------------------------------------------------------------------
CREATE TABLE end_users (
  user_key    integer GENERATED BY DEFAULT AS IDENTITY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  external_id text NOT NULL,

  email_ciphertext bytea,
  email_key_id     text,
  email_type       text CHECK (email_type IN ('work', 'free', 'education', 'disposable')),

  -- name, firstName, lastName, company: anything that identifies a person.
  name_traits_ciphertext bytea,
  name_traits_key_id     text,

  -- Everything else from identify(): plan, role, teamSize and so on.
  traits      jsonb NOT NULL DEFAULT '{}'::jsonb,

  country     text,
  -- First referrer, campaign and landing page: credits payers to the channel that
  -- found them (brief Appendix A).
  first_touch jsonb NOT NULL DEFAULT '{}'::jsonb,
  visits_before_signup  integer NOT NULL DEFAULT 0,
  days_before_signup    integer,

  signed_up_at   timestamptz,
  activated_at   timestamptz,
  paid_at        timestamptz,
  trial_started_at timestamptz,
  trial_ends_at    timestamptz,
  card_required    boolean,

  -- Writable only with a secret key. The join key to the later Stripe layer.
  stripe_customer_id text,

  account_id  integer,
  -- The founder's own team, kept out of every number.
  internal    boolean NOT NULL DEFAULT false,
  -- No alerts about this person (brief section 8.3).
  opted_out   boolean NOT NULL DEFAULT false,

  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_event_at timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  deleted_at    timestamptz,
  PRIMARY KEY (project_id, user_key)
);
CREATE UNIQUE INDEX end_users_project_external_key ON end_users (project_id, external_id);
CREATE INDEX end_users_project_stripe_idx ON end_users (project_id, stripe_customer_id)
  WHERE stripe_customer_id IS NOT NULL;
CREATE INDEX end_users_project_last_event_idx ON end_users (project_id, last_event_at DESC);

-- ---------------------------------------------------------------------------
-- anonymous_visitors / anonymous_links — how a visit becomes a person.
--
-- Events keep the anonymous key they were written with FOREVER. identify() never
-- rewrites an old row; it writes a link, and the timeline is joined through that link
-- by time (brief section 4). A second person identifying on the same anonymous id
-- starts a new link from that moment, so two people are never merged.
-- ---------------------------------------------------------------------------
CREATE TABLE anonymous_visitors (
  anon_key    integer GENERATED BY DEFAULT AS IDENTITY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  anonymous_id text NOT NULL,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  session_count integer NOT NULL DEFAULT 0,
  PRIMARY KEY (project_id, anon_key)
);
CREATE UNIQUE INDEX anonymous_visitors_project_id_key
  ON anonymous_visitors (project_id, anonymous_id);

CREATE TABLE anonymous_links (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  anon_key    integer NOT NULL,
  user_key    integer NOT NULL,
  linked_at   timestamptz NOT NULL,
  -- The window of event time this link claims. The first link for an anonymous id
  -- claims everything before it too, which is how pre-signup visits join the person.
  claims_from timestamptz NOT NULL DEFAULT '-infinity',
  claims_to   timestamptz NOT NULL DEFAULT 'infinity',
  PRIMARY KEY (project_id, anon_key, linked_at),
  FOREIGN KEY (project_id, anon_key) REFERENCES anonymous_visitors (project_id, anon_key) ON DELETE CASCADE,
  FOREIGN KEY (project_id, user_key) REFERENCES end_users (project_id, user_key) ON DELETE CASCADE
);
CREATE INDEX anonymous_links_user_idx ON anonymous_links (project_id, user_key);

-- ---------------------------------------------------------------------------
-- accounts / account_members — from group(). Account funnels and scores.
-- ---------------------------------------------------------------------------
CREATE TABLE accounts (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  external_id text NOT NULL,
  name        text,
  domain      text,
  plan        text,
  seats       integer,
  -- Minor units plus a currency code, never a float.
  monthly_revenue_amount   integer,
  monthly_revenue_currency text,
  traits      jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at  timestamptz NOT NULL DEFAULT now(),
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, id)
);
CREATE UNIQUE INDEX accounts_project_external_key ON accounts (project_id, external_id);

CREATE TABLE account_members (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  account_id  integer NOT NULL,
  user_key    integer NOT NULL,
  role        text,
  joined_via  text,
  joined_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, account_id, user_key),
  FOREIGN KEY (project_id, account_id) REFERENCES accounts (project_id, id) ON DELETE CASCADE,
  FOREIGN KEY (project_id, user_key) REFERENCES end_users (project_id, user_key) ON DELETE CASCADE
);
CREATE INDEX account_members_user_idx ON account_members (project_id, user_key);

ALTER TABLE end_users
  ADD CONSTRAINT end_users_account_fkey
  FOREIGN KEY (project_id, account_id) REFERENCES accounts (project_id, id) ON DELETE SET NULL;

-- ---------------------------------------------------------------------------
-- sessions — one row per visit, about 210 bytes. THIS is where context lives, once,
-- instead of on every event.
-- ---------------------------------------------------------------------------
CREATE TABLE sessions (
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  -- Client-generated; the session NUMBER below is derived on the server.
  client_session_id text NOT NULL,
  anon_key    integer,
  user_key    integer,
  session_number integer NOT NULL DEFAULT 1,

  started_at  timestamptz NOT NULL,
  ended_at    timestamptz,
  active_seconds integer NOT NULL DEFAULT 0,
  page_count  integer NOT NULL DEFAULT 0,

  -- The 18 context fields of brief Appendix A, section A.
  device_type text CHECK (device_type IN ('desktop', 'mobile', 'tablet')),
  os          text,
  browser     text,
  browser_major text,
  screen_bucket text CHECK (screen_bucket IN ('small', 'medium', 'large')),
  language    text,
  timezone    text,
  country     text,
  referrer_domain text,
  utm_source  text,
  utm_medium  text,
  utm_campaign text,
  utm_term    text,
  utm_content text,
  -- Yes/no plus the network. The ad-click id itself is discarded (brief section 10).
  paid_click  boolean NOT NULL DEFAULT false,
  paid_network text,
  landing_path_id integer,
  consent_granted boolean,
  global_privacy_control boolean,
  library_name text,
  library_version text,

  PRIMARY KEY (project_id, id)
);
CREATE UNIQUE INDEX sessions_project_client_key ON sessions (project_id, client_session_id);
CREATE INDEX sessions_project_user_idx ON sessions (project_id, user_key, started_at DESC)
  WHERE user_key IS NOT NULL;
CREATE INDEX sessions_project_anon_idx ON sessions (project_id, anon_key, started_at DESC);

-- ---------------------------------------------------------------------------
-- events — the compact table. See the byte budget at the top of this file.
-- ---------------------------------------------------------------------------
CREATE TABLE events (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  -- The first 16 bytes of sha256(messageId), as a uuid: 16 bytes with no varlena
  -- header, and it is all dedupe needs. The client's own id is echoed back from
  -- memory, so nothing is lost by not storing the text.
  message_hash uuid NOT NULL,
  name_id     integer NOT NULL,
  -- Exactly one of these is set at write time; identify() never rewrites the other.
  user_key    integer,
  anon_key    integer,
  session_id  bigint,
  -- Skew-corrected device time: when it actually happened.
  occurred_at timestamptz NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  path_id     integer,
  -- Only the properties the catalog names, and only when they are present.
  props       jsonb,
  -- browser | server | segment | rudderstack | posthog | billing, as a small integer.
  source      smallint NOT NULL,
  -- Bit 0: late (received more than an hour after it happened).
  flags       smallint NOT NULL DEFAULT 0,

  -- Dedupe. A replayed batch changes nothing (brief section 5).
  PRIMARY KEY (project_id, message_hash)
);
-- One person's timeline, newest first.
CREATE INDEX events_project_user_time_idx ON events (project_id, user_key, occurred_at DESC)
  WHERE user_key IS NOT NULL;
-- Counts per event name per day, and the funnel.
CREATE INDEX events_project_name_time_idx ON events (project_id, name_id, occurred_at DESC);
-- The retention job deletes by time range. BRIN costs almost nothing per row on an
-- append-ordered table and is exactly right for a range scan (brief section 10).
CREATE INDEX events_received_brin_idx ON events USING brin (received_at) WITH (pages_per_range = 32);

-- ---------------------------------------------------------------------------
-- user_step_state — about 103 bytes. Updated in the same transaction as the event.
-- Order-insensitive on purpose: it keeps the EARLIEST entered and EARLIEST completed
-- time, so a late or out-of-order event can never corrupt it (brief section 5).
-- ---------------------------------------------------------------------------
CREATE TABLE funnels (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  name        text NOT NULL DEFAULT 'Onboarding',
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, id)
);
-- One active onboarding funnel per project (brief section 4).
CREATE UNIQUE INDEX funnels_one_active_per_project ON funnels (project_id) WHERE is_active;

CREATE TABLE funnel_steps (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  funnel_id   integer NOT NULL,
  position    integer NOT NULL,
  -- The founder's own name for the step, shown everywhere in the UI.
  label       text NOT NULL,
  -- A step is reached by an event name or by a URL rule.
  event_name  text,
  url_rule_id integer,
  -- Every step before Activated starts as Key (brief section 8.1).
  importance  text NOT NULL DEFAULT 'normal' CHECK (importance IN ('key', 'normal', 'optional')),
  -- "under 2 minutes": flags users who take longer. Optional.
  expected_seconds integer,
  -- Overrides the 24-hour stall default for this step (settled decision 8).
  stall_override_seconds integer,
  PRIMARY KEY (project_id, id),
  FOREIGN KEY (project_id, funnel_id) REFERENCES funnels (project_id, id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX funnel_steps_position_key ON funnel_steps (project_id, funnel_id, position);

CREATE TABLE url_rules (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  -- e.g. '/onboarding/step-*' or '/pricing'
  pattern     text NOT NULL,
  -- The canonical meaning a matching page view becomes.
  canonical   text NOT NULL,
  -- For an onboarding step rule: which step.
  step_label  text,
  is_key_page boolean NOT NULL DEFAULT false,
  position    integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, id)
);
CREATE INDEX url_rules_project_idx ON url_rules (project_id, position);

ALTER TABLE funnel_steps
  ADD CONSTRAINT funnel_steps_url_rule_fkey
  FOREIGN KEY (project_id, url_rule_id) REFERENCES url_rules (project_id, id) ON DELETE SET NULL;

CREATE TABLE user_step_state (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  user_key    integer NOT NULL,
  step_id     integer NOT NULL,
  first_entered_at   timestamptz,
  first_completed_at timestamptz,
  attempts    integer NOT NULL DEFAULT 0,
  -- Separate sessions spent on this step.
  visits      integer NOT NULL DEFAULT 0,
  active_seconds integer NOT NULL DEFAULT 0,
  last_event_at  timestamptz,
  PRIMARY KEY (project_id, user_key, step_id),
  FOREIGN KEY (project_id, user_key) REFERENCES end_users (project_id, user_key) ON DELETE CASCADE,
  FOREIGN KEY (project_id, step_id) REFERENCES funnel_steps (project_id, id) ON DELETE CASCADE
);
-- "Users stuck now", per step.
CREATE INDEX user_step_state_stuck_idx ON user_step_state (project_id, step_id, first_entered_at)
  WHERE first_completed_at IS NULL;

-- ---------------------------------------------------------------------------
-- Volume guards and counting (brief section 4).
-- ---------------------------------------------------------------------------

-- The daily cap: past N rows per user per event type per day we count instead of
-- storing, so a track() call stuck in a loop cannot fill the database.
CREATE TABLE daily_event_counts (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  day         date NOT NULL,
  user_key    integer NOT NULL,
  name_id     integer NOT NULL,
  -- Everything that arrived. stored_count and overflow_count are derived from it,
  -- so "was this row stored?" is a single comparison and never off by one.
  total_count    integer NOT NULL DEFAULT 0,
  stored_count   integer NOT NULL DEFAULT 0,
  -- How many we counted instead of storing. Surfaced in tracking health.
  overflow_count integer NOT NULL DEFAULT 0,
  PRIMARY KEY (project_id, day, user_key, name_id)
);

-- One conflict-ignored insert per user per month gives exact tracked-user counts.
CREATE TABLE monthly_active_users (
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  month       date NOT NULL,
  user_key    integer NOT NULL,
  PRIMARY KEY (project_id, month, user_key)
);

-- Token buckets per key, in Postgres to start (brief section 5).
CREATE TABLE rate_buckets (
  api_key_id  uuid PRIMARY KEY REFERENCES api_keys (id) ON DELETE CASCADE,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  tokens      double precision NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Row-level security on everything added here, same rules as 0001.
-- ---------------------------------------------------------------------------
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'event_names', 'paths', 'end_users', 'anonymous_visitors', 'anonymous_links',
    'accounts', 'account_members', 'sessions', 'events', 'funnels', 'funnel_steps',
    'url_rules', 'user_step_state', 'daily_event_counts', 'monthly_active_users',
    'rate_buckets'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY %I ON %I USING (project_id = app_current_project_id()) WITH CHECK (project_id = app_current_project_id())',
      t || '_scoped', t);
    EXECUTE format(
      'CREATE POLICY %I ON %I USING (app_rls_bypassed()) WITH CHECK (app_rls_bypassed())',
      t || '_bypass', t);
  END LOOP;
END
$$;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO dripmetric_app;
