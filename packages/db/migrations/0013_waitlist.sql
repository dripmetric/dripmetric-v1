-- 0013_waitlist.sql — the landing page's waitlist, in the product's own database.
--
-- Why here and not in a form service: when signup opens, the founders on this list are
-- the first people invited, and an invite is a join on the email address. Keeping the
-- list beside founder_users makes that a query instead of an import
-- (docs/decisions.md, 2026-11-20).
--
-- Who can touch it. The landing page is a public website, so its database credential
-- is the one most likely to leak. It therefore gets its own role, `dripmetric_site`,
-- which can do exactly two things: add an address, and mark a fresh address as handed
-- to the welcome-mail automation. It cannot read the list, not even its own rows, and
-- it cannot reach any other table. A leaked site credential adds rows; it never
-- reveals one.

-- ---------------------------------------------------------------------------
-- The site role. NOLOGIN here, like dripmetric_app: the migrate CLI gives it a
-- development password, and production sets its own out of band (docs/runbook.md).
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dripmetric_site') THEN
    CREATE ROLE dripmetric_site NOLOGIN;
  END IF;
END
$$;

-- A runaway request from the public site gives up rather than holding a connection.
ALTER ROLE dripmetric_site SET statement_timeout = '5s';

-- ---------------------------------------------------------------------------
-- waitlist — one row per address.
-- ---------------------------------------------------------------------------
CREATE TABLE waitlist (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- As typed, trimmed. Uniqueness is on lower(email), below.
  email         text NOT NULL CHECK (char_length(email) BETWEEN 3 AND 254 AND position('@' IN email) > 1),
  -- Which form: 'hero' or 'final' today. Free text within a tight shape, so a new form
  -- does not need a migration.
  source        text NOT NULL CHECK (source ~ '^[a-z0-9-]{1,32}$'),
  created_at    timestamptz NOT NULL DEFAULT now(),
  -- The outbox column. NULL until the address has been handed to the welcome-mail
  -- automation, so every address that arrives while the automation is off (or down)
  -- is still waiting to be sent when it comes on: `pnpm waitlist:forward`.
  forwarded_at  timestamptz
);

-- A double submit, or the same person on two forms, is one row.
CREATE UNIQUE INDEX waitlist_email_key ON waitlist (lower(email));
-- What `pnpm waitlist:forward` reads.
CREATE INDEX waitlist_unforwarded_idx ON waitlist (created_at) WHERE forwarded_at IS NULL;

-- Deny by default (CLAUDE.md, hard invariants). RLS on and NO policy, so every role
-- other than the owner sees and changes nothing. Not FORCEd: the owner is who runs
-- migrations and the two functions below, and those are the only ways in.
ALTER TABLE waitlist ENABLE ROW LEVEL SECURITY;

-- 0001's default privileges hand dripmetric_app DML on every new table. The founder
-- app has no use for the waitlist yet; the invite flow will grant what it needs, with
-- a policy, in its own migration.
REVOKE ALL ON waitlist FROM PUBLIC;
REVOKE ALL ON waitlist FROM dripmetric_app;

-- ---------------------------------------------------------------------------
-- The only two ways in. SECURITY DEFINER, so they run as the owner; a fixed
-- search_path, so a caller cannot redirect `waitlist` to a table of their own.
-- ---------------------------------------------------------------------------

-- Adds an address. Returns the new row's id, or NULL when the address was already on
-- the list. The site answers both the same way, so the form cannot be used to find
-- out who has signed up.
CREATE FUNCTION waitlist_join(p_email text, p_source text) RETURNS bigint
LANGUAGE sql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  INSERT INTO public.waitlist (email, source)
  VALUES (p_email, p_source)
  ON CONFLICT ((lower(email))) DO NOTHING
  RETURNING id
$$;

-- Records that a NEW address was handed to the automation. Only rows from the last
-- 15 minutes, so a leaked site credential cannot mark the whole list as sent and stop
-- the backlog from going out. The site calls this seconds after waitlist_join.
CREATE FUNCTION waitlist_mark_forwarded(p_id bigint) RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  WITH marked AS (
    UPDATE public.waitlist
       SET forwarded_at = now()
     WHERE id = p_id
       AND forwarded_at IS NULL
       AND created_at > now() - interval '15 minutes'
    RETURNING 1
  )
  SELECT EXISTS (SELECT 1 FROM marked)
$$;

-- Functions are executable by PUBLIC unless revoked.
REVOKE ALL ON FUNCTION waitlist_join(text, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION waitlist_mark_forwarded(bigint) FROM PUBLIC;

GRANT USAGE ON SCHEMA public TO dripmetric_site;
GRANT EXECUTE ON FUNCTION waitlist_join(text, text) TO dripmetric_site;
GRANT EXECUTE ON FUNCTION waitlist_mark_forwarded(bigint) TO dripmetric_site;

-- ---------------------------------------------------------------------------
-- Supabase's Data API roles.
--
-- On Supabase, everything created in `public` is granted to `anon`, `authenticated`
-- and `service_role` by default, which would put the table and both functions behind
-- the project's REST API. Dripmetric never uses that API (docs/runbook.md says to
-- switch it off), and this takes the grants back in case it is on. On plain Postgres
-- the roles do not exist and nothing happens.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  api_role text;
BEGIN
  FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
      EXECUTE format('REVOKE ALL ON waitlist FROM %I', api_role);
      EXECUTE format('REVOKE ALL ON FUNCTION waitlist_join(text, text) FROM %I', api_role);
      EXECUTE format('REVOKE ALL ON FUNCTION waitlist_mark_forwarded(bigint) FROM %I', api_role);
    END IF;
  END LOOP;
END
$$;
